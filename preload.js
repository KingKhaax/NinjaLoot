'use strict';
const { contextBridge, ipcRenderer, webFrame } = require('electron');
contextBridge.exposeInMainWorld('api', {
  fetchReport: id => ipcRenderer.invoke('report:fetch', id),
  parseLoot: text => ipcRenderer.invoke('loot:parse', text),
  lookupItems: (ids, lang) => ipcRenderer.invoke('items:lookup', ids, lang),
  iconData: href => ipcRenderer.invoke('icon:data', href),
  itemTooltip: (id, ilvl, lang) => ipcRenderer.invoke('items:tooltip', id, ilvl, lang),
  getBosses: () => ipcRenderer.invoke('bosses:get'),
  fetchGear: (region, realm, name) => ipcRenderer.invoke('gear:fetch', region, realm, name),
  fetchPortrait: (region, realm, name) => ipcRenderer.invoke('portrait:fetch', region, realm, name),
  fetchVault: (region, realm, name) => ipcRenderer.invoke('vault:fetch', region, realm, name),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: asset => ipcRenderer.invoke('update:install', asset),
  onUpdateProgress: cb => ipcRenderer.on('update:progress', (_e, f) => cb(f)),
  discordGet: () => ipcRenderer.invoke('discord:get'),
  discordSet: o => ipcRenderer.invoke('discord:set', o),
  discordInvite: () => ipcRenderer.invoke('discord:invite'),
  rosterGuild: (region, realm, name) => ipcRenderer.invoke('roster:guild', region, realm, name),
  onDiscordSims: cb => ipcRenderer.on('discord:sims', (_e, ids) => cb(ids)),
  onDiscordStatus: cb => ipcRenderer.on('discord:status', (_e, s) => cb(s)),
  setZoom: f => webFrame.setZoomFactor(Math.min(1.6, Math.max(0.7, Number(f) || 1))),
  appInfo: () => ipcRenderer.invoke('app:info'),
  openExternal: url => ipcRenderer.invoke('app:open', url),
});
